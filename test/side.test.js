'use strict';
const { BASE, ok, wait, shot, launch, post, addHost, devices, hostKey } = require('./helpers');
const { Server, utils } = require('ssh2');
let cols = 0;
new Server({ hostKeys: [hostKey()] }, (c) => {
  c.on('authentication', (ctx) => ctx.accept());
  c.on('ready', () => c.on('session', (acc) => { const s = acc(); s.on('pty', (a, r, i) => { cols = i.cols; a(); }); s.on('window-change', (a, r, i) => { cols = i.cols; a && a(); });
    s.on('shell', (a) => { const st = a(); st.write('$ '); }); }));
}).listen(2227, '127.0.0.1');
(async () => {
  await fetch(BASE + '/api/hosts', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'S', host: '127.0.0.1', port: 2227, username: 'u', password: 'x' }) });
  const browser = await launch();
  const errors = [];
  const p = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage(); p.on('pageerror', (e) => errors.push(e.message));
  await p.goto(BASE + '/'); await p.waitForSelector('#app:not(.hidden)');
  await p.locator('.host', { hasText: 'S' }).click(); await wait(1200);
  ok(await p.isVisible('#btnSideClose'), '电脑：侧边栏顶部有关闭按钮');
  await p.screenshot({ path: shot('side-desk-open.png') });
  const c0 = cols;
  await p.click('#btnSideClose'); await wait(500);
  ok(await p.isHidden('#sidebar') && cols > c0, `点 ✕ 收起侧边栏，终端变宽 ${c0} → ${cols} 列`);
  ok(await p.evaluate(() => document.activeElement.id) === 'dInput', '收起后焦点回到输入框');
  await p.click('#btnToggle'); await wait(500);
  ok(await p.isVisible('#sidebar') && cols === c0, '☰ 重新打开');
  await p.click('#btnToggle'); await wait(300); ok(await p.isHidden('#sidebar'), '☰ 仍可切换收起');
  await p.click('#btnToggle'); await wait(300);
  const m = await (await browser.newContext({ ...devices['Pixel 7'] })).newPage(); m.on('pageerror', (e) => errors.push(e.message));
  await m.goto(BASE + '/'); await m.waitForSelector('.tab'); await wait(1000);
  const shown = () => m.evaluate(() => { const r = document.getElementById('sidebar').getBoundingClientRect(); return r.right > 5; });
  ok(!(await shown()), '手机：侧边栏默认收起');
  await m.tap('#btnToggle'); await wait(400);
  ok(await shown() && await m.isVisible('#btnSideClose'), '手机：☰ 打开后顶部有关闭按钮');
  await m.screenshot({ path: shot('side-mobile-open.png') });
  await m.tap('#btnSideClose'); await wait(400);
  ok(!(await shown()), '手机：点 ✕ 关闭侧边栏');
  await m.tap('#btnToggle'); await wait(400); ok(await shown(), '手机：再次 ☰ 打开');
  ok(errors.length === 0, '无页面错误 ' + errors.join('; '));
  await browser.close(); process.exit();
})().catch((e) => { console.error(e); process.exit(1); });
